#!/usr/bin/env python3
"""Generates `known.rs`: the BAML known types and known properties.

Read from WPF's `PresentationFramework/System/Windows/Markup/KnownTypes.cs`
(github.com/dotnet/wpf, MIT): the `KnownElements` and `KnownProperties`
enums, whose values a BAML record names a built-in type or property by, and
the full name of each element's type (`typeof(...)` in the type lookup).

Usage: generate_known.py <KnownTypes.cs> <wpf commit> > known.rs
"""
import re
import sys

source = open(sys.argv[1], encoding="utf-8").read()
commit = sys.argv[2]


def enum(name):
    start = source.index("internal enum " + name)
    body = source[source.index("{", start) + 1:source.index("}", start)]
    body = re.sub(r"//.*", "", body)
    return [item.split("=")[0].strip() for item in body.split(",") if item.strip()]


elements = enum("KnownElements")
properties = enum("KnownProperties")
full = dict(re.findall(r"case KnownElements\.(\w+): t = typeof\(([\w.]+)\); break;", source))
index = {name: i for i, name in enumerate(elements)}

out = []
out.append("//! The BAML known types and known properties: the built-in WPF types and")
out.append("//! properties a BAML record names by a negative identifier instead of a")
out.append("//! `TypeInfo` or `AttributeInfo` record.")
out.append("//!")
out.append("//! Generated by `generate_known.py` from WPF's `KnownTypes.cs`")
out.append(f"//! (github.com/dotnet/wpf, MIT, commit `{commit}`): the `KnownElements`")
out.append("//! and `KnownProperties` enums in order, each element's full type name from")
out.append("//! its `typeof`. Do not edit by hand.")
out.append("")
out.append("/// The known types by `KnownElements` value: each type's full name, or")
out.append("/// `None` for the enum's sentinels (`UnknownElement`, `MaxElement`).")
out.append("pub(crate) const KNOWN_TYPES: &[Option<&str>] = &[")
for name in elements:
    out.append(f'    Some("{full[name]}"),' if name in full else "    None,")
out.append("];")
out.append("")
out.append("/// The known properties by `KnownProperties` value: the index of the known")
out.append("/// type that declares each and its name, or `None` for the sentinels")
out.append("/// (`UnknownProperty`, `MaxProperty`).")
out.append("pub(crate) const KNOWN_PROPERTIES: &[Option<(u16, &str)>] = &[")
for name in properties:
    owner, sep, prop = name.partition("_")
    if sep and owner in index:
        out.append(f'    Some(({index[owner]}, "{prop}")),')
    else:
        out.append("    None,")
out.append("];")
print("\n".join(out))
